/* The title's sprite palettes.  fade_screen_in() uploads its single 16-byte
 * argument to both the background and the sprite palettes, so a 16-byte title
 * palette cannot keep sprite palette 1 yellow or palette 2 the menu blue: the
 * sprite palettes would copy the background rows.  The title therefore fades
 * its sprite palettes from this array instead (see fade_title_in).  These four
 * rows must equal SP0-SP3 in palettes/title.txt: the engine recognises a
 * palette by the colours in it, so if the sprite rows differ the title palette
 * is not recognised when the game returns to the title screen and the game's
 * palette stays on screen (the sound-test digits then show in game colours). */
