#!/usr/bin/env node
'use strict';

/**
 * build.js -- Alter Ego title-screen PoC build script
 *
 * 1. Generate the palette management (palettes.s, pal_transitions.s, pal_defs.s)
 *    from palettes/.
 * 2. Convert the CHR-ROM held by PPU.s into the 64KB tiledata bank and assemble
 *    the game.  The NES code is the original HEAD C build at $8000-$FFFF,
 *    placed by rom.s; the support/shim code is below $8000 in the same bank.
 */

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { generatePalettes, PaletteError } = require('../../../scripts/generate-palette-transitions.js');
const { buildNromGame } = require('../../../scripts/lib/nromBuild.js');

// What Q does is a property of the disk the application is on, so it is a build switch (Main.s)
// rather than a run-time check -- see the comment at `quit` in Main.s for why looking for the Finder
// with GS/OS does not work.
//
//   default        quit to the Finder (the full System 6 volume has one)
//   --boot         the 800 KiB boot disk, which has no Finder: Q restarts the game
//   --exitscreen   ... or Q leaves the game for good: the screen says so and only a reset returns
//   --autotest     dev only: quit as soon as the game starts, so the quit path needs no key press
const bootDisk = process.argv.includes('--boot');
const exitScreen = process.argv.includes('--exitscreen');
const autoTest = process.argv.includes('--autotest');
if (bootDisk && exitScreen) {
  console.error('Error: --boot and --exitscreen are two different answers to Q; pick one.');
  process.exit(1);
}
fs.writeFileSync(
  path.join(__dirname, 'QuitMode.s'),
  `; Generated by build.js -- do not edit.  See the comment at "quit" in Main.s.\n` +
    `QUIT_RESTARTS equ ${bootDisk ? 1 : 0}\n` +
    `QUIT_EXITSCREEN equ ${exitScreen ? 1 : 0}\n` +
    `QUIT_AT_BOOT  equ ${autoTest ? 1 : 0}\n`
);

// The quit screen is a Super Hi-Res bitmap rendered at build time from the game's own CHR font
// (scripts/make-quit-screen.mjs -> quitscreen.bin, assembled by TileData.s).  Only the build that
// uses it needs it.
if (exitScreen) {
  const genArgs = [path.join(__dirname, '..', '..', '..', 'scripts', 'make-quit-screen.mjs')];
  if (process.argv.includes('--test')) genArgs.push('--test'); // throwaway: four pixel orders, one row each
  execFileSync(process.execPath, genArgs, { stdio: 'inherit' });
}

const palettesDir = path.join(__dirname, 'palettes');
try {
  generatePalettes({
    transitionsFile: path.join(palettesDir, 'transitions.txt'),
    palettesDir,
    outDir: __dirname,
  });
} catch (e) {
  if (!(e instanceof PaletteError)) throw e;
  console.error(`Error: ${e.message}`);
  process.exit(1);
}

buildNromGame(__dirname, 'AlterEgo.s');

// Publish the assembled load file next to the boot image, i.e. in build/ (the VERA port
// keeps its images in vera/build/ the same way).  Merlin32 writes its DSK into the game
// directory, which stays local and is ignored.  Each variant is published under its own
// name so the builds cannot overwrite each other.
const publishDir = path.join(__dirname, '..', '..', '..', 'build');
const publishName = bootDisk ? 'AlterEgoGS.boot' : exitScreen ? 'AlterEgoGS.exit' : 'AlterEgoGS';
fs.mkdirSync(publishDir, { recursive: true });
fs.copyFileSync(path.join(__dirname, 'AlterEgoGS'), path.join(publishDir, publishName));
console.log(`  published ${path.relative(process.cwd(), path.join(publishDir, publishName))}`);
