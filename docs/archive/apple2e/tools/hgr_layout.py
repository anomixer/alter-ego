"""Generate the HGR scanline address table.

Layout (verified against two independent sources in C:/dev/pom2games):

  dev/lib/hgr/hgr_scanline.inc   addr[y] = $2000 + (y%8)*$0400 + ((y/8)%8)*$80 + (y/64)*$28
  dev/lib/hgrc/hgr_layout.h      HGR_ROW_ADDR(base,y) = base<<8 + ((y&7)<<10)
                                            + (((y>>3)&7)<<7) + (y>>6)*40

Both agree:  1024 -> (y % 8),  128 -> ((y // 8) % 8),  40 -> (y // 64).

An earlier version of this file attached those same coefficients to the wrong
terms (2560*(y//64) + 320*((y//8)%8) + 40*(y%8)).  That is still a permutation
of 192 disjoint 40-byte bands, so a pure overlap check passes -- which is
exactly why the bug survived a self-consistency test.  The hardware layout
fills the page exactly ($3FF8 + 40 = $4000); the wrong one stops at $3E00.

Emitted format: hgr_line_off is a 192-entry table of 16-bit words, consumed as
	lda hgr_line_off,y
	sta ptr
	lda hgr_line_off+1,y
	sta ptr+1
"""

BASE = 0x2000
LINES = 192
BYTES_PER_LINE = 40


def line_off(y):
    """Byte offset of HGR scanline y from the page base."""
    return 1024 * (y % 8) + 128 * ((y // 8) % 8) + 40 * (y // 64)


def check():
    ivs = sorted((line_off(y), line_off(y) + BYTES_PER_LINE) for y in range(LINES))
    overlaps = sum(1 for i in range(len(ivs) - 1) if ivs[i][1] > ivs[i + 1][0])
    span = ivs[-1][1] - ivs[0][0]
    return overlaps, span, len(set(ivs))


def main():
    overlaps, span, distinct = check()
    print('span=$%04X..$%04X  bytes used=%d (page=8192)  distinct=%d  overlaps=%d'
          % (BASE, BASE + span - BYTES_PER_LINE, BYTES_PER_LINE * LINES, distinct, overlaps))
    if overlaps or distinct != LINES:
        raise SystemExit('scanline layout is not a clean permutation')
    if BASE + span > 0x4000:
        raise SystemExit('layout runs past the 8 KB page: ends at $%04X'
                         % (BASE + span))
    # The 192 bands are 40-byte slots inside 0..8184, so the page tail is
    # intentionally sparse: the last band ends at $3FF8, 8 bytes short of $4000.
    print('page tail unused: $%04X..$3FFF (%d bytes)' % (BASE + span, 0x4000 - (BASE + span)))


    out = ['; generated by tools/hgr_layout.py -- do not edit',
           '; HGR scanline -> page address (page base $2000)',
           '; addr[y] = base + (y%%8)*$0400 + ((y/8)%%8)*$80 + (y/64)*$28',
           '; DHGR uses the same scanline addressing (dhgr.c:19-25 resolves',
           '; addr = HGR_ROW_ADDR(base,y) + (byte>>1)), so the DHGR modules alias',
           '; this table instead of carrying a second copy.',
           '.export hgr_line_off',
           '.export dhgr_line_off := hgr_line_off',
           'hgr_line_off:']
    for i in range(0, LINES, 8):
        vals = ', '.join('$%04X' % (BASE + line_off(y)) for y in range(i, i + 8))
        out.append('\t.word %s\t; y=%d' % (vals, i))
    out.append('')

    with open('build/hgr_lines.s', 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(out))
    print('wrote build/hgr_lines.s')
    for y in (0, 1, 7, 8, 64, 128, 191):
        print('  y=%-3d -> $%04X' % (y, BASE + line_off(y)))


if __name__ == '__main__':
    main()
