#!/usr/bin/env python3
"""Generate the DHGR scanline -> address table for the Apple //e.

VERIFIED LAYOUT (no longer a hypothesis).  Source: C:/dev/pom2games GPL-3.0 dev
kit, dev/lib/hgrc/dhgr.c lines 19-25, cross-checked against
dev/lib/hgr/hgr_scanline.inc.  See docs/PORT-APPLE2-EVAL.md section 13.2.

    byte = x / 7                       # x is the 560 px coordinate -> 0..79
    addr = HGR_ROW_ADDR(base, y) + (byte >> 1)
    aux  = (byte & 1) ^ 1              # even byte -> AUX, odd byte -> MAIN
    HGR_ROW_ADDR(base, y) = base + 1024*(y%8) + 128*((y//8)%8) + 40*(y//64)

Consequences:
  * The scanline table is IDENTICAL to the HGR one.  DHGR does not have its own
    interleaving; it reuses the HGR one and splits each 40-byte row across the
    two banks by byte parity.
  * One line = 80 bytes = 40 main + 40 aux, at the SAME 40 addresses.
  * One page = 15,360 bytes (7,680 main + 7,680 aux), not 16 KB and not 30,720.
  * Page 1 base $2000, page 2 base $4000.
  * Colour: color_bits(c) = ((c>>1)|(c<<3)) & 15; pattern = color_bits*0x1111;
    the four bytes are (pattern >> ((i*7)&3)) & 0x7F for
    i = 0,1,2,3 == [aux-even, main-even, aux-odd, main-odd]  (shifts 0,3,2,1).

The engine consumes `dhgr_line_off` as 192 words, exactly like hgr.s does with
hgr_line_off, and applies the parity rule itself.
"""
import sys

BASE = 0x2000          # DHGR page 1; page 2 is $4000
LINES = 192
BPL = 80               # bytes per scanline, counting both banks
BANK_BYTES = 40        # bytes per scanline inside one bank


def row_off(y):
    """Offset of scanline y inside the page (verified formula)."""
    return 1024 * (y % 8) + 128 * ((y // 8) % 8) + 40 * (y // 64)


def slot(y, byte):
    """Return (address, bank) for the byte index (0..79) of scanline y."""
    if not 0 <= byte < BPL:
        raise ValueError('byte index out of range: %d' % byte)
    return BASE + row_off(y) + (byte >> 1), ('aux' if (byte & 1) == 0 else 'main')


def self_check():
    seen = {'main': set(), 'aux': set()}
    for y in range(LINES):
        row = BASE + row_off(y)
        for b in range(BPL):
            addr, bank = slot(y, b)
            if not row <= addr <= row + BANK_BYTES - 1:
                raise AssertionError('y=%d byte=%d escapes the row: $%04X' % (y, b, addr))
            seen[bank].add((y, addr))
        # the 40 main slots must be exactly row..row+39, same for aux
        mains = sorted(addr for _, addr, bank in
                       [(None, slot(y, b)[0], slot(y, b)[1]) for b in range(BPL)]
                       if bank == 'main')
        auxs = sorted(addr for _, addr, bank in
                      [(None, slot(y, b)[0], slot(y, b)[1]) for b in range(BPL)]
                      if bank == 'aux')
        expect = [row + i for i in range(BANK_BYTES)]
        if mains != expect or auxs != expect:
            raise AssertionError('y=%d banks are not row..row+39' % y)
    print('DHGR layout self-check: %d lines OK' % LINES)
    print('  main slots total = %d, aux slots total = %d (expect %d each)'
          % (len(seen['main']), len(seen['aux']), LINES * BANK_BYTES))
    for y in (0, 1, 8, 64, 191):
        row = BASE + row_off(y)
        print('  y=%-3d row=$%04X  main=$%04X..$%04X  aux=$%04X..$%04X'
              % (y, row, row, row + BANK_BYTES - 1, row, row + BANK_BYTES - 1))
    print('  page bytes = %d (main %d + aux %d)'
          % (LINES * BPL, LINES * BANK_BYTES, LINES * BANK_BYTES))


def colour_patterns():
    """The 16 DHGR colours as the four bank/parity pattern bytes."""
    names = ['BLACK', 'MAGENTA', 'DARKBLUE', 'VIOLET', 'DARKGREEN', 'GRAY1',
             'BLUE', 'LIGHTBLUE', 'BROWN', 'ORANGE', 'GRAY2', 'PINK', 'GREEN',
             'YELLOW', 'AQUA', 'WHITE']
    out = []
    for c in range(16):
        bits = ((c >> 1) | (c << 3)) & 15
        pattern = bits * 0x1111
        pats = [(pattern >> ((i * 7) & 3)) & 0x7F for i in range(4)]
        assert all(p < 0x80 for p in pats), 'colour %d produced a full byte' % c
        out.append((c, names[c], bits, pats))
    return out


def emit(path):
    offs = [row_off(y) for y in range(LINES)]
    if len(set(offs)) != LINES:
        raise AssertionError('scanline offsets are not distinct')
    max_used = max(offs) + BANK_BYTES
    if BASE + max_used > 0x4000:
        raise AssertionError('page 1 overruns $4000: $%04X' % (BASE + max_used))
    with open(path, 'w', encoding='utf-8') as f:
        f.write('; generated by tools/dhgr_layout.py -- do not edit\n')
        f.write('; DHGR scanline -> row base, IDENTICAL to the HGR layout.\n')
        f.write('; byte 0..79 of a line: addr = row + (byte>>1); even byte -> aux,\n')
        f.write('; odd byte -> main.  Page 1 base $2000, page 2 base $4000.\n')
        f.write('.export dhgr_line_off\n')
        f.write('dhgr_line_off:\n')
        for y in range(0, LINES, 8):
            vals = ', '.join('$%04X' % (BASE + o) for o in offs[y:y + 8])
            f.write('\t.word %s\t; y=%d\n' % (vals, y))
    print('wrote %s' % path)
    print('  span=$%04X..$%04X  page bytes=%d (main+aux)'
          % (BASE + min(offs), BASE + max(offs) + BANK_BYTES, LINES * BPL))
    print('  y=0 -> $%04X   y=8 -> $%04X   y=64 -> $%04X   y=191 -> $%04X'
          % (BASE + offs[0], BASE + offs[8], BASE + offs[64], BASE + offs[191]))


def main():
    out = r'C:\dev\alter-ego\build\dhgr_lines.s'
    args = sys.argv[1:]
    for i, a in enumerate(args):
        if a == '--out' and i + 1 < len(args):
            out = args[i + 1]
    self_check()
    print()
    for c, name, bits, pats in colour_patterns():
        print('  colour %2d %-10s bits=%s  pattern[aux-even,main-even,aux-odd,main-odd]=%s'
              % (c, name, format(bits, '04b'),
                 ' '.join('$%02X' % p for p in pats)))
    print()
    emit(out)


if __name__ == '__main__':
    main()
