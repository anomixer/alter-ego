#!/usr/bin/env python3
"""Emit src/a2/music_offsets.h from the music link map.

The FamiTone image is linked at its runtime address (src/a2/a2_music.cfg), so
the eight module addresses are decided by the link.  Reading them out of the
map keeps game.c's musicData[] in step with the image automatically: change a
track, relink, regenerate, and the pointers follow.  Nothing is hand-written.

Usage:  python tools/a2_music_offsets.py build/a2/music.map
"""
import re
import sys

# Declaration order in src/a2/a2_music.cfg, matching musicData[] in src/game.c.
ORDER = [
    ("MUS_TIT", "MUSPTR_TITLE"),
    ("MUS_L1",  "MUSPTR_GAME1"),
    ("MUS_L2",  "MUSPTR_GAME2"),
    ("MUS_L3",  "MUSPTR_GAME3"),
    ("MUS_L4",  "MUSPTR_GAME4"),
    ("MUS_L5",  "MUSPTR_GAME5"),
    ("MUS_OVR", "MUSPTR_GAMEOVER"),
    ("MUS_DON", "MUSPTR_WELLDONE"),
]

# Levels whose module was dropped from src/a2/music_image.s for space reuse an
# existing track.  src/a2/music_image.s explains the byte budget.
ALIAS = {"MUS_L3": "MUS_L1", "MUS_L4": "MUS_L2", "MUS_L5": "MUS_L1"}

# Memory-map row: "MUS_TIT   004A45  004C9D  000259  00001"
ROW = re.compile(r"^\s*(MUS_[A-Z0-9]+)\s+([0-9A-Fa-f]{4,6})\s+([0-9A-Fa-f]{4,6})\s+([0-9A-Fa-f]{4,6})")


def main():
    map_path = sys.argv[1] if len(sys.argv) > 1 else "build/a2/music.map"
    out_path = sys.argv[2] if len(sys.argv) > 2 else "src/a2/music_offsets.h"

    addrs = {}
    with open(map_path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = ROW.match(line)
            if m:
                addrs[m.group(1)] = int(m.group(2), 16)

    missing = [seg for seg, _ in ORDER
               if seg not in addrs and ALIAS.get(seg) not in addrs]
    if missing:
        sys.exit("map has no memory-map rows for: %s" % ", ".join(missing))

    base = addrs["MUS_INS"]
    lines = [
        "/* Generated by tools/a2_music_offsets.py from the music link map.",
        "   Do not edit: relink src/a2/music_image.s and regenerate.",
        "",
        "   The FamiTone image is linked at its runtime address because every",
        "   module embeds absolute pointers to its channel streams and to the",
        "   instrument table, so the addresses below are the addresses the",
        "   bytes were assembled for.  The disk file MUSIC is BLOAD-ed to",
        "   $%04X at startup (src/a2/lvload.s: lv_assets). */" % base,
        "",
        "#ifndef A2_MUSIC_OFFSETS_H",
        "#define A2_MUSIC_OFFSETS_H",
        "",
        "#define MUSIC_BASE   0x%04Xu" % base,
        "",
    ]
    for seg, name in ORDER:
        addr = addrs[seg] if seg in addrs else addrs[ALIAS[seg]]
        lines.append("#define %-12s ((const unsigned char *)0x%04Xu)"
                     % (name, addr))
    lines += ["", "#endif /* A2_MUSIC_OFFSETS_H */", ""]

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print("wrote %s" % out_path)
    for seg, name in ORDER:
        src = seg if seg in addrs else ALIAS[seg]
        print("  %-12s $%04X%s" % (name, addrs[src],
                                   "" if src == seg else "   (alias of %s)" % src))
    resolved = [addrs[seg] if seg in addrs else addrs[ALIAS[seg]]
                for seg, _ in ORDER]
    print("  image base $%04X, last block starts $%04X" % (base, max(resolved)))


if __name__ == "__main__":
    main()

