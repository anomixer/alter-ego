#!/usr/bin/env python3
"""Emit src/a2/cold_stubs.s from the cold image link map.

src/a2/ftm.s and src/a2/sys.s are linked on their own at $D000 (the Apple //e
language-card RAM bank, src/a2/a2_cold.cfg) and shipped as the disk file COLD,
which src/a2/lvload.s BLOAD-s at startup.  The program calls them through the
jump stubs written here, so the two images do not have to be linked together.

The addresses are not hand-written.  ld65 has no --cfgsym option (checked
against ld65 --help), so they come out of the verbose map file (-vm), whose
global-symbol block lists every exported name with its address.  Relink the
cold image, rerun this, and the stubs follow.

Usage:  python tools/a2_cold_stubs.py build/a2/cold.map src/a2/cold_stubs.s
"""
import re
import sys

# Every routine the program reaches across the boundary.  These are the
# exports of src/a2/ftm.s and src/a2/sys.s that neslib.c declares.
EXPORTS = [
    "_tick_frame",
    "_timer_start",
    "_timer_read",
    "_input_poll",
    "_input_last_key",
    "_mb_init",
    "_mb_present",
    "_ftm_play",
    "_ftm_stop",
    "_ftm_tick",
    "_ftm_playing",
    "_sfx_start",
    "_sfx_stop_all",
    "_ftm_pause",
]

# Verbose map row: "_ftm_tick   00D1A4  LA"
SYM = re.compile(r"(_[A-Za-z0-9_]+)\s+([0-9A-Fa-f]{4,6})\s+LA")


def main():
    map_path = sys.argv[1] if len(sys.argv) > 1 else "build/a2/cold.map"
    out_path = sys.argv[2] if len(sys.argv) > 2 else "src/a2/cold_stubs.s"

    text = open(map_path, "r", encoding="utf-8", errors="replace").read()
    addrs = {}
    for m in SYM.finditer(text):
        addrs.setdefault(m.group(1), int(m.group(2), 16))

    missing = [name for name in EXPORTS if name not in addrs]
    if missing:
        sys.exit("cold map has no address for: %s" % ", ".join(missing))

    base = min(addrs[n] for n in EXPORTS)
    lines = [
        "; Generated by tools/a2_cold_stubs.py from the cold image link map.",
        "; Do not edit: relink src/a2/a2_cold.cfg and regenerate.",
        ";",
        "; src/a2/ftm.s and src/a2/sys.s are linked at $D000, in the Apple //e",
        "; language-card RAM bank, and loaded from the disk file COLD by",
        "; src/a2/lvload.s: lv_assets.  Each stub is a tail jump, so the",
        "; fastcall arguments in A and X pass straight through and the routine's",
        "; own RTS returns to this stub's caller.",
        "",
        ".segment \"CODE\"",
        "",
    ]
    for name in EXPORTS:
        lines.append(".export %s" % name)
    lines.append("")
    for name in EXPORTS:
        lines.append("%s:" % name)
        lines.append("        jmp     $%04X                    ; %s"
                     % (addrs[name], name))
        lines.append("")
    lines.append("; cold image spans $%04X-$%04X"
                 % (base, max(addrs[n] for n in EXPORTS)))
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print("wrote %s" % out_path)
    for name in EXPORTS:
        print("  %-16s $%04X" % (name, addrs[name]))


if __name__ == "__main__":
    main()
