#!/usr/bin/env python3
"""Emit src/a2/tsmap.inc: the DOS 3.3 track/sector entry point and sector count
for every file the game streams with RWTS.

The disk is packed by the kit's dos33.py, which writes T/S list sectors in the
real DOS 3.3 layout:

    offset $01,$02 : track, sector of the next list sector ($00,$00 = none)
    offset $05,$06 : 16-bit index of the first pair this list sector covers
    offset $0C..   : 122 (track, sector) pairs, little-endian pairs

so a reader only has to read the first list sector and walk its pairs while it
still has sectors left.  Files here are 1..3 data sectors, so one list sector
always covers them.

Output is a ca65 include, one 4-byte record per level:
    list track, list sector, data sector count, spare
"""
import struct
import sys

SEC = 256
VTOC_T, VTOC_S = 0, 3


def main():
    dsk = sys.argv[1]
    out = sys.argv[2]
    want = sys.argv[3:]           # file names to emit, in order

    raw = open(dsk, 'rb').read()
    if len(raw) % (16 * SEC) != 0 or len(raw) < 3 * 16 * SEC:
        print('unexpected image size %d (not a whole number of tracks)' % len(raw))
        return 1
    tracks = len(raw) // (16 * SEC)

    def sector(t, s):
        off = t * 16 * SEC + s * SEC
        sec = raw[off:off + SEC]
        if len(sec) != SEC:
            raise SystemExit('sector (%d,%d) outside the image' % (t, s))
        return sec

    # The kit's packer writes the VTOC at track 17 sector 0 (the DOS 3.3 master
    # layout: DOS on 0-2, user area from 17).  Find it by signature rather than
    # assuming, so the reader also works on a 140-track master image where the
    # VTOC sits at track 2 sector 3.
    vtoc = None
    for t in range(tracks):
        cand = sector(t, 0)
        if cand[0] == 0x04 and cand[3] == 0x03 and cand[1] < tracks and cand[2] < 16:
            vtoc = (t, 0)
            break
    if vtoc is None:
        for t in range(tracks):
            cand = sector(t, 3)
            if cand[0] == 0x04 and cand[3] == 0x03 and cand[1] < tracks and cand[2] < 16:
                vtoc = (t, 3)
                break
    if vtoc is None:
        print('no VTOC found')
        return 1
    print('VTOC at track %d sector %d' % vtoc)

    cat_t, cat_s = sector(*vtoc)[1], sector(*vtoc)[2]

    files = {}
    order = []
    for i in range(35):
        s = cat_s - (i // 7)
        sec = sector(cat_t, s)
        e = 0x0B + (i % 7) * 35
        if sec[e] == 0:
            continue
        tl, sl, ftype = sec[e], sec[e + 1], sec[e + 2]
        name = ''.join(chr(c & 0x7F) for c in sec[e + 3:e + 33]).strip()
        nsect = struct.unpack('<H', sec[e + 33:e + 35])[0]
        files[name] = (tl, sl, ftype & 0x7F, nsect)
        order.append(name)

    lines = [
        ';-----------------------------------------------------------------------',
        '; tsmap.inc -- generated by tools/a2_tsmap.py from the packed disk.',
        '; One 4-byte record per streamed file: T/S-list track, T/S-list sector,',
        '; data sector count, spare.',
        '; lvload.s reads the list sector and walks its pairs from offset $0C.',
        ';-----------------------------------------------------------------------',
    ]

    missing = [n for n in want if n not in files]
    if missing:
        print('not on disk: %s' % ' '.join(missing))
        return 1

    for name in want:
        tl, sl, ftype, nsect = files[name]
        # Data sectors = total sectors claimed minus the list sectors.
        lists = (nsect + 121) // 122
        data = nsect - lists
        # Payload length: walk the list and count the non-zero pairs.
        lsec = sector(tl, sl)
        pairs = []
        t, s = tl, sl
        while True:
            sec = sector(t, s)
            for k in range(122):
                dt, ds = sec[0x0C + 2 * k], sec[0x0D + 2 * k]
                if (dt, ds) == (0, 0):
                    break
                pairs.append((dt, ds))
            nt, ns = sec[1], sec[2]
            if nt == 0 and ns == 0:
                break
            t, s = nt, ns
        if len(pairs) != data:
            print('%s: %d pairs in the list, catalog claims %d data sectors'
                  % (name, len(pairs), data))
            return 1
        lines.append('  .byte $%02X, $%02X, %d, $00   ; %s'
                     % (tl, sl, data, name))

    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote %s (%d entries)' % (out, len(want)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
